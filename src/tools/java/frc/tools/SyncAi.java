package frc.tools;

import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Stream;

/**
 * Generates GitHub Copilot files from the Claude Code ones: {@code .claude/rules/*.md} to {@code
 * .github/instructions/*.instructions.md}, and {@code .claude/agents/*.md} to {@code
 * .github/agents/*.agent.md}. With {@code --check} it only reports drift.
 */
public final class SyncAi {
  private SyncAi() {}

  static final String MARKER = "GENERATED by `frc sync-ai`";

  /** Entry point: {@code sync-ai [--check]}. Returns the exit code. */
  public static int run(Path root, boolean check, PrintStream out, PrintStream err) {
    Map<String, String> expected;
    try {
      expected = expected(root);
    } catch (IOException e) {
      err.println("frc: " + e.getMessage());
      return 2;
    }
    List<String> drift = new ArrayList<>();
    for (Map.Entry<String, String> e : expected.entrySet()) {
      Path file = root.resolve(e.getKey());
      String actual = read(file);
      if (!e.getValue().equals(actual)) {
        drift.add((actual == null ? "missing: " : "out of date: ") + e.getKey());
        if (!check) {
          try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, e.getValue(), StandardCharsets.UTF_8);
          } catch (IOException ex) {
            err.println("frc: could not write " + e.getKey() + ": " + ex.getMessage());
            return 2;
          }
        }
      }
    }
    for (String orphan : orphans(root, expected.keySet())) {
      drift.add("orphan (no source): " + orphan);
      if (!check) {
        try {
          Files.deleteIfExists(root.resolve(orphan));
        } catch (IOException ex) {
          err.println("frc: could not delete " + orphan + ": " + ex.getMessage());
          return 2;
        }
      }
    }
    if (check) {
      if (drift.isEmpty()) {
        out.println("{\"syncAi\":\"ok\",\"files\":" + expected.size() + "}");
        return 0;
      }
      drift.forEach(d -> err.println("frc sync-ai: " + d));
      err.println("frc sync-ai: Copilot files are out of date. Run ./frc sync-ai and commit.");
      return 1;
    }
    out.println(
        "{\"syncAi\":\"written\",\"files\":"
            + expected.size()
            + ",\"changed\":"
            + drift.size()
            + "}");
    return 0;
  }

  /** The files that should exist, by path relative to the repository root. */
  static Map<String, String> expected(Path root) throws IOException {
    Map<String, String> files = new LinkedHashMap<>();
    for (Path rule : list(root.resolve(".claude/rules"), ".md")) {
      String name = stripSuffix(rule.getFileName().toString(), ".md");
      files.put(
          ".github/instructions/" + name + ".instructions.md",
          renderInstruction(read(rule), ".claude/rules/" + rule.getFileName()));
    }
    for (Path agent : list(root.resolve(".claude/agents"), ".md")) {
      String name = stripSuffix(agent.getFileName().toString(), ".md");
      files.put(
          ".github/agents/" + name + ".agent.md",
          renderAgent(read(agent), ".claude/agents/" + agent.getFileName()));
    }
    return files;
  }

  /** Generated files in the output folders whose source no longer exists. */
  static List<String> orphans(Path root, Set<String> expected) {
    List<String> out = new ArrayList<>();
    for (String dir : List.of(".github/instructions", ".github/agents")) {
      try {
        for (Path p : list(root.resolve(dir), ".md")) {
          String rel = dir + "/" + p.getFileName();
          String text = read(p);
          if (text != null && text.contains(MARKER) && !expected.contains(rel)) {
            out.add(rel);
          }
        }
      } catch (IOException ignored) {
        // Missing folder: nothing to check
      }
    }
    return out;
  }

  /** Renders a Copilot path-specific instructions file from a Claude rule. */
  static String renderInstruction(String source, String sourcePath) {
    Front f = Front.parse(source);
    List<String> paths = f.list("paths");
    String applyTo = paths.isEmpty() ? "**" : String.join(",", paths);
    return "---\napplyTo: " + quote(applyTo) + "\n---\n" + header(sourcePath) + f.body;
  }

  /** Renders a Copilot custom agent from a Claude subagent. Models are not mapped. */
  static String renderAgent(String source, String sourcePath) {
    Front f = Front.parse(source);
    Set<String> tools = new LinkedHashSet<>();
    for (String t : f.csv("tools")) {
      switch (t) {
        case "Read" -> tools.add("read");
        case "Grep", "Glob" -> tools.add("search");
        case "Edit", "Write", "MultiEdit", "NotebookEdit" -> tools.add("edit");
        case "Bash" -> tools.add("execute");
        case "WebFetch", "WebSearch" -> tools.add("web");
        default -> {}
      }
    }
    StringBuilder sb = new StringBuilder("---\n");
    sb.append("name: ").append(f.get("name")).append('\n');
    sb.append("description: ").append(quote(f.get("description"))).append('\n');
    sb.append("tools: [")
        .append(String.join(", ", tools.stream().map(SyncAi::quote).toList()))
        .append("]\n---\n");
    return sb + header(sourcePath) + f.body;
  }

  private static String header(String sourcePath) {
    return "<!-- "
        + MARKER
        + " from "
        + sourcePath
        + ". Do not edit this file: edit the source and run `./frc sync-ai`. -->\n\n";
  }

  private static String quote(String s) {
    return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
  }

  private static String stripSuffix(String s, String suffix) {
    return s.endsWith(suffix) ? s.substring(0, s.length() - suffix.length()) : s;
  }

  private static List<Path> list(Path dir, String suffix) throws IOException {
    if (!Files.isDirectory(dir)) {
      return List.of();
    }
    try (Stream<Path> s = Files.list(dir)) {
      return s.filter(p -> p.getFileName().toString().endsWith(suffix)).sorted().toList();
    }
  }

  private static String read(Path p) {
    try {
      return Files.exists(p)
          ? Files.readString(p, StandardCharsets.UTF_8).replace("\r\n", "\n")
          : null;
    } catch (IOException e) {
      return null;
    }
  }

  /** Minimal YAML front matter: scalar fields and one-level lists. */
  static final class Front {
    final Map<String, String> scalars = new LinkedHashMap<>();
    final Map<String, List<String>> lists = new LinkedHashMap<>();
    String body = "";

    static Front parse(String text) {
      Front f = new Front();
      if (text == null) {
        return f;
      }
      String[] lines = text.replace("\r\n", "\n").split("\n", -1);
      int i = 0;
      if (lines.length > 0 && lines[0].equals("---")) {
        i = 1;
        String listKey = null;
        while (i < lines.length && !lines[i].equals("---")) {
          String line = lines[i];
          if (line.startsWith("  - ") || line.startsWith("- ")) {
            if (listKey != null) {
              f.lists.get(listKey).add(unquote(line.substring(line.indexOf('-') + 1).trim()));
            }
          } else if (line.contains(":")) {
            int c = line.indexOf(':');
            String key = line.substring(0, c).trim();
            String value = line.substring(c + 1).trim();
            if (value.isEmpty()) {
              listKey = key;
              f.lists.put(key, new ArrayList<>());
            } else {
              listKey = null;
              f.scalars.put(key, unquote(value));
            }
          }
          i++;
        }
        i++; // skip closing ---
      }
      StringBuilder body = new StringBuilder();
      for (int j = i; j < lines.length; j++) {
        body.append(lines[j]);
        if (j < lines.length - 1) {
          body.append('\n');
        }
      }
      f.body = body.toString();
      return f;
    }

    String get(String key) {
      return scalars.getOrDefault(key, "");
    }

    List<String> list(String key) {
      return lists.getOrDefault(key, List.of());
    }

    List<String> csv(String key) {
      List<String> out = new ArrayList<>();
      for (String s : get(key).split(",")) {
        if (!s.isBlank()) {
          out.add(s.trim());
        }
      }
      return out;
    }

    private static String unquote(String s) {
      if (s.length() >= 2
          && (s.startsWith("\"") && s.endsWith("\"") || s.startsWith("'") && s.endsWith("'"))) {
        return s.substring(1, s.length() - 1);
      }
      return s;
    }
  }
}
